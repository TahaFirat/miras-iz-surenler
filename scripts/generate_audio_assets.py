"""
Studio-Grade Natural Turkish Male Storytelling Narration Generator
Model: Microsoft Edge Neural Voice (`tr-TR-AhmetNeural`, natural warm male storyteller)
Encodes crisp 36kbps mono AAC .m4a clips into assets/audio/*.m4a and updates src/utils/audioAssets.ts.
"""
import argparse
import asyncio
import json
import os
import re
import tempfile
import time
import av


def clean_text(t: str) -> str:
    t = re.sub(r"[💡⚡▶★✓🎁📖🏛️🛡️⚙️🔍🧭❤️✨🪶📜🏆]", " ", t)
    t = t.replace("?.", "?").replace("!.", "!")
    t = re.sub(r"\s+", " ", t).strip()
    return t


def transcode_mp3_to_m4a(mp3_bytes: bytes, out_path: str, bitrate: int = 36000) -> None:
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    tmp_mp3 = out_path + ".tmp.mp3"
    tmp_m4a = out_path + ".tmp.m4a"
    with open(tmp_mp3, "wb") as f:
        f.write(mp3_bytes)
    try:
        ic = av.open(tmp_mp3)
        oc = av.open(tmp_m4a, mode="w", format="ipod")
        istream = ic.streams.audio[0]
        ostream = oc.add_stream("aac", rate=24000, layout="mono")
        ostream.bit_rate = bitrate
        resampler = av.AudioResampler(format="fltp", layout="mono", rate=24000)
        for frame in ic.decode(istream):
            for rf in resampler.resample(frame):
                for pkt in ostream.encode(rf):
                    oc.mux(pkt)
        for pkt in ostream.encode(None):
            oc.mux(pkt)
        oc.close()
        ic.close()
        os.replace(tmp_m4a, out_path)
    finally:
        if os.path.exists(tmp_mp3):
            os.remove(tmp_mp3)
        if os.path.exists(tmp_m4a):
            os.remove(tmp_m4a)


def write_audio_assets_ts(out_dir: str) -> int:
    files = sorted(
        f for f in os.listdir(out_dir) if f.endswith(".m4a") and not f.endswith(".tmp.m4a")
    )
    ts_path = os.path.abspath(
        os.path.join(os.path.dirname(__file__), "..", "src", "utils", "audioAssets.ts")
    )
    lines = [
        "// Auto-generated by scripts/generate_audio_assets.py using Studio Turkish Male Voice (tr-TR-AhmetNeural)",
        "export const AUDIO_ASSETS: Record<string, number> = {",
    ]
    for fn in files:
        cid = fn[:-4]
        lines.append(f'  "{cid}": require("../../assets/audio/{fn}"),')
    lines.append("};")
    with open(ts_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    return len(files)


async def edge_worker(
    worker_id: int,
    queue: asyncio.Queue,
    out_dir: str,
    force: bool,
    bitrate: int,
    stats: dict,
):
    import edge_tts

    while True:
        try:
            job = queue.get_nowait()
        except asyncio.QueueEmpty:
            return
        clip_id = job["id"]
        out_file = os.path.join(out_dir, f"{clip_id}.m4a")
        if not force and os.path.exists(out_file) and os.path.getsize(out_file) > 3000:
            stats["done"] += 1
            queue.task_done()
            continue
        text = clean_text(job["text"])
        if not text:
            queue.task_done()
            continue

        last_err = None
        for attempt in range(4):
            try:
                comm = edge_tts.Communicate(
                    text, voice="tr-TR-AhmetNeural", rate="-5%", pitch="-2Hz"
                )
                chunks = []
                async for msg in comm.stream():
                    if msg["type"] == "audio":
                        chunks.append(msg["data"])
                mp3_bytes = b"".join(chunks)
                if len(mp3_bytes) < 1000:
                    raise RuntimeError("Empty audio response")
                await asyncio.to_thread(transcode_mp3_to_m4a, mp3_bytes, out_file, bitrate)
                stats["done"] += 1
                if stats["done"] % 25 == 0 or stats["done"] == stats["total"]:
                    print(f"[STUDIO] {stats['done']}/{stats['total']} done", flush=True)
                last_err = None
                break
            except Exception as e:
                last_err = e
                await asyncio.sleep(1.5 * (attempt + 1))
        if last_err is not None:
            print(f"[STUDIO ERR] {clip_id}: {last_err}", flush=True)
        queue.task_done()


async def run_edge_all(
    jobs: list, out_dir: str, concurrency: int, force: bool, bitrate: int
):
    queue = asyncio.Queue()
    for j in jobs:
        queue.put_nowait(j)
    stats = {"done": 0, "total": len(jobs)}
    workers = [
        asyncio.create_task(
            edge_worker(i, queue, out_dir, force, bitrate, stats)
        )
        for i in range(concurrency)
    ]
    await asyncio.gather(*workers)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--concurrency", type=int, default=12)
    parser.add_argument("--bitrate", type=int, default=36000)
    parser.add_argument("--force", action="store_true")
    parser.add_argument("--jobs", type=str, default="miras_tts_jobs_v2.json")
    args = parser.parse_args()

    jobs_path = os.path.join(tempfile.gettempdir(), args.jobs)
    with open(jobs_path, "r", encoding="utf-8") as f:
        jobs = json.load(f)

    out_dir = os.path.abspath(
        os.path.join(os.path.dirname(__file__), "..", "assets", "audio")
    )
    os.makedirs(out_dir, exist_ok=True)

    t0 = time.time()
    print(
        f"Synthesizing {len(jobs)} studio male narration clips (tr-TR-AhmetNeural, concurrency={args.concurrency})...",
        flush=True,
    )
    asyncio.run(
        run_edge_all(jobs, out_dir, args.concurrency, args.force, args.bitrate)
    )
    count = write_audio_assets_ts(out_dir)
    elapsed = time.time() - t0
    print(f"ALL DONE in {elapsed:.1f}s! Total M4A clips registered: {count}", flush=True)


if __name__ == "__main__":
    main()
