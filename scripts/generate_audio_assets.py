def clean_text(t: str) -> str:
    t = re.sub(r"[💡⚡▶★✓🎁📖🏛️🛡️⚙️🔍🧭❤️✨🪶]", " ", t)
    t = re.sub(r"\s+", " ", t).strip()
    return t

def encode_m4a(audio: np.ndarray, out_path: str, bitrate: int = 24000) -> None:
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    tmp_path = out_path + ".tmp.m4a"
    container = av.open(tmp_path, mode="w", format="ipod")
    stream = container.add_stream("aac", rate=RATE, layout="mono")
    stream.bit_rate = bitrate
    pcm = np.clip(audio, -1.0, 1.0)
    chunk_size = 4096
    for i in range(0, len(pcm), chunk_size):
        seg = pcm[i : i + chunk_size]
        frame = av.AudioFrame.from_ndarray(
            seg[np.newaxis, :].astype(np.float32), format="fltp", layout="mono"
        )
        frame.sample_rate = RATE
        for pkt in stream.encode(frame):
            container.mux(pkt)
    for pkt in stream.encode(None):
        container.mux(pkt)
    container.close()
    os.replace(tmp_path, out_path)

def write_audio_assets_ts(out_dir: str) -> int:
    files = sorted(f for f in os.listdir(out_dir) if f.endswith(".m4a") and not f.endswith(".tmp.m4a"))
    ts_path = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "src", "utils", "audioAssets.ts"))
    lines = [
        "// Auto-generated by scripts/generate_audio_assets.py using erkamk/yazgi-tts-1 (Apache-2.0, male-01)",
        "export const AUDIO_ASSETS: Record<string, number> = {",
    ]
    for fn in files:
        cid = fn[:-4]
        lines.append(f'  "{cid}": require("../../assets/audio/{fn}"),')
    lines.append("};")
    with open(ts_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    return len(files)

def run_worker(worker_idx: int, num_workers: int, jobs: list, out_dir: str) -> None:
    device = "cuda" if torch.cuda.is_available() else "cpu"
    tts = YazgiTTS(device=device, pronunciations=PRONUNCIATIONS)
    shard = [j for i, j in enumerate(jobs) if i % num_workers == worker_idx]
    done = 0
    for job in shard:
        clip_id = job["id"]
        out_file = os.path.join(out_dir, f"{clip_id}.m4a")
        if os.path.exists(out_file) and os.path.getsize(out_file) > 2000:
            done += 1
            continue
        text = clean_text(job["text"])
        if not text:
            continue
        try:
            audio = tts.say(text, voice="male-01", seed=42, temperature=0.68, pred_temperature=0.25)
            encode_m4a(audio, out_file, bitrate=24000)
            done += 1
            if done % 10 == 0 or done == len(shard):
                print(f"[W{worker_idx}] {done}/{len(shard)} done", flush=True)
        except Exception as e:
            print(f"[W{worker_idx} ERR] {clip_id}: {e}", flush=True)

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--workers", type=int, default=4)
    parser.add_argument("--worker-idx", type=int, default=-1)
    args = parser.parse_args()

    jobs_path = os.path.join(tempfile.gettempdir(), "miras_tts_jobs.json")
    with open(jobs_path, "r", encoding="utf-8") as f:
        jobs = json.load(f)

    out_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "assets", "audio"))
    os.makedirs(out_dir, exist_ok=True)

    # Clean leftover temp files
    for fn in os.listdir(out_dir):
        if fn.endswith(".tmp.m4a"):
            os.remove(os.path.join(out_dir, fn))

    if args.worker_idx >= 0:
        run_worker(args.worker_idx, args.workers, jobs, out_dir)
        return

    print(f"Launching {args.workers} parallel GPU workers for {len(jobs)} clips...", flush=True)
    t0 = time.time()
    procs = []
    for wi in range(args.workers):
        p = subprocess.Popen([sys.executable, "-u", __file__, "--workers", str(args.workers), "--worker-idx", str(wi)])
        procs.append(p)
    for p in procs:
        p.wait()

    count = write_audio_assets_ts(out_dir)
    print(f"ALL DONE in {(time.time()-t0)/60:.1f} min! Total M4A clips registered: {count}", flush=True)

if __name__ == "__main__":
    main()
